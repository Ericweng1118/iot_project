-- 2. 把剩下的 threshold_percent 門檻值顯性化（todo.md 待辦 #2）
--    原本 upload_threshold 全是 NULL、靠程式碼 fallback 成 1%，
--    等於「門檻寫在程式裡而不是資料裡」。這裡補成顯式的 1，行為完全不變，
--    但網頁後台看得到實際生效的數字，日後要調整也不用改程式碼。
-- ----------------------------------------------------------------------------
UPDATE sensors
   SET upload_threshold = 1
 WHERE upload_threshold IS NULL
   AND upload_condition IN ('threshold_percent', 'threshold_absolute');

