-- 目的：把「累計型計數器」的上傳判斷方式從 threshold_percent 改成 on_change。
--
-- 背景（2026-09-11 排查）
-- ------------------------------------------------------------------
-- v2 的統一寫入排程（data_layer/timeseries_writer.py）改用 sensors.upload_condition
-- 逐感測器判斷「這一輪要不要寫」。006 把所有感測器的預設值設成 threshold_percent，
-- 而 upload_threshold 全部是 NULL，程式會 fallback 成 1%。
--
-- 這個預設值對「即時值」型的點位（即時功耗、溫度、壓力、液位…）沒問題，
-- 但對「累計型計數器」是錯的語意：累計電表的基準值可以到百萬等級，日增量卻只有
-- 幾百，變化 1% 要累積四十幾天。實測結果是 126 個 threshold_percent 感測器裡有
-- 47 個超過一天完全沒有新資料，而且**每一個**的變化量都低於 1%：
--
--     sensor 126 (B06累計功耗)：上次寫入 1,137,169（2026-09-03 16:50）
--                               目前值   1,139,354（+2,185，僅 0.1921%）
--                               要達到 1% 需要 +11,371.69，約還要 41 天
--
-- OPC UA 連線、訂閱、數值全部正常，純粹是門檻判斷擋下來的。
--
-- 為什麼選 on_change 而不是 threshold_absolute
-- ------------------------------------------------------------------
-- 累計型計數器單調遞增，「值跟上次寫入不一樣就寫」正是它要的語意，
-- 不需要為每一支電表/流量計各自猜一個絕對門檻值。寫入頻率的上限由
-- SENSOR_READING_FLUSH_INTERVAL（目前 60 秒）決定，等同 v1 的行為。
-- 若日後要降低資料量，再改成 threshold_absolute 並依各點位的工程單位設定門檻。
--
-- 名單怎麼來的
-- ------------------------------------------------------------------
-- 命名規則（累計 / 累積 / 總流量 / 總功率 / 運轉時間 / 加載時間 / 正流向 / 負流向，
-- 且不含「即時」）交叉比對近 30 天 sensor_readings 的單調性，兩者一致。
-- 唯一的 4 筆不一致（92 / 95 / 96 / 134）逐筆檢查過，下降事件都是數值「掉到 0」
-- 的設備重啟或通訊異常，不是真正的即時值，因此仍歸類為累計型。
--
-- 安全性
-- ------------------------------------------------------------------
-- - 只改 sensors 的設定欄位，不動任何既有的 sensor_readings 資料。
-- - 可重複執行。WHERE 有 upload_condition = 'threshold_percent' 這道保護，
--   所以日後若手動把某支調成別的設定，再次整批重跑 sql/0*.sql 也不會被蓋掉。
-- - 回滾腳本：sql/010_rollback.sql
-- ============================================================================

